export function 그리기(자리, 하위) {
  if (하위 === 'why') 위험그리기(자리);
  else if (하위 === 'portal') 포털그리기(자리);
  else if (하위 === 'sort') 정리그리기(자리);
  else 더찾기그리기(자리);
}

