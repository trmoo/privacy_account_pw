    const 종류 = [/[A-Za-z]/, /[0-9]/, /[^A-Za-z0-9]/].filter((re) => re.test(v)).length;
    const 길이 = [...v].length;
    const 우리기준 = (종류 >= 2 && 길이 >= 10) || (종류 >= 3 && 길이 >= 8);
    const r = 검사(v);
