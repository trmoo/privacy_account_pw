// 대문자를 어디에 넣었는지 맞히는 경우의 수. 첫 글자만·끝 글자만·모두 대문자는 해커가 먼저 시도해서 ×2 뿐이다.
export function 대문자경우(토막) {
  const 대 = (토막.match(/[A-Z]/g) || []).length;
  const 소 = (토막.match(/[a-z]/g) || []).length;
  if (대 === 0) return 1;
  if (소 === 0 || /^[A-Z][^A-Z]*$/.test(토막) || /^[^A-Z]*[A-Z]$/.test(토막)) return 2;
  let 경우 = 0;
  for (let i = 1; i <= Math.min(대, 소); i++) 경우 += 조합(대 + 소, i);
  return 경우;
}

