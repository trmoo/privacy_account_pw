function 리트찾기(글자, 결과) {
  const n = 글자.length;
  for (let i = 0; i < n; i++) {
    for (let j = i + 2; j < Math.min(n, i + 16); j++) {
      const 토막 = 글자.slice(i, j + 1);
      if (!토막.some((c) => 리트표[c])) continue;
      // 바꿀 수 있는 글자마다 「그대로 / 바꿈」 을 모두 만들어 본다 (최대 64가지)
      let 후보 = [{ 글: '', 바꿈: [] }];
      for (const c of 토막) {
        const 다음 = [];
        for (const h of 후보) {
          다음.push({ 글: h.글 + c.toLowerCase(), 바꿈: h.바꿈 });
          for (const 글자로 of 리트표[c] || []) 다음.push({ 글: h.글 + 글자로, 바꿈: [...h.바꿈, `${c}→${글자로}`] });
        }
        후보 = 다음.slice(0, 64);
      }
      const 원 = 토막.join('');
      for (const h of 후보) {
        if (!h.바꿈.length) continue;
        const 가지 = new Set(h.바꿈).size;
        const 곱 = 대문자경우(원) * 2 ** 가지;
        const 순 = 흔한표.get(h.글) ?? 영어표.get(h.글) ?? 이름표.get(h.글);
        if (순) 결과.push(조각(i, j, 원, '리트', 순 * 곱, { 낱말: h.글, 바꿈: [...new Set(h.바꿈)] }));
      }
    }
  }
}

// 연속 — abcd · 1234 · 9876 · !@#$ (Shift+1234)
const 기호줄 = '!@#$%^&*()';
function 연속칸(c) {
  if (/[a-z]/.test(c)) return { 무리: '소', 번호: c.charCodeAt(0) };
  if (/[A-Z]/.test(c)) return { 무리: '대', 번호: c.charCodeAt(0) };
  if (/[0-9]/.test(c)) return { 무리: '숫', 번호: c.charCodeAt(0) };
  const k = 기호줄.indexOf(c);
  return k >= 0 ? { 무리: '기', 번호: k } : null;
}
function 연속차이(가, 나) {
  const a = 연속칸(가);
  const b = 연속칸(나);
  if (!a || !b || a.무리 !== b.무리) return 0;
  // 자판 숫자 줄은 1234567890 이라 9 다음이 0 이다
  if (가 === '9' && 나 === '0') return 1;
  if (가 === '0' && 나 === '9') return -1;
  const d = b.번호 - a.번호;
  return Math.abs(d) === 1 ? d : 0;
}
function 연속찾기(글자, 결과) {
  let i = 0;
  while (i < 글자.length - 2) {
    const d = 연속차이(글자[i], 글자[i + 1]);
    if (!d) { i++; continue; }
    let j = i + 1;
    while (j + 1 < 글자.length && 연속차이(글자[j], 글자[j + 1]) === d) j++;
    if (j - i + 1 >= 3) {
      const 첫 = 글자[i];
      const 밑 = 'aAzZ019!'.includes(첫) ? 4 : /[0-9]/.test(첫) || 기호줄.includes(첫) ? 10 : 26;
      const 추측 = 밑 * (j - i + 1) * (d < 0 ? 2 : 1);
      결과.push(조각(i, j, 글자.slice(i, j + 1).join(''), '연속', 추측, { 거꾸로: d < 0 }));
      i = j + 1;
    } else i++;
  }
}

// 되풀이 — aaaa · 1111 · abcabc. 덩이 하나를 맞히면 나머지는 공짜다.
function 되풀이찾기(글자, 결과, 덩이검사) {
  const n = 글자.length;
  for (let i = 0; i < n; i++) {
    let 가장 = null;
    for (let b = 1; b <= Math.floor((n - i) / 2); b++) {
      const 덩이 = 글자.slice(i, i + b).join('');
      let r = 1;
      while (i + (r + 1) * b <= n && 글자.slice(i + r * b, i + (r + 1) * b).join('') === 덩이) r++;
      if (r >= (b === 1 ? 3 : 2) && (!가장 || r * b > 가장.r * 가장.덩이.length)) 가장 = { 덩이, r };
    }
    if (가장) {
      const 길이 = 가장.r * [...가장.덩이].length;
      const 덩이lg = 덩이검사(가장.덩이);
      결과.push(조각(i, i + 길이 - 1, 글자.slice(i, i + 길이).join(''), '되풀이', { lg: 덩이lg + lg(가장.r) }, { 덩이: 가장.덩이, 횟수: 가장.r }));
    }
  }
}

