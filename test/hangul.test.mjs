import { 묶음, 확인, 참 } from './harness.mjs';
import { 한글을자판으로, 자판을한글로, 한영풀이 } from '../src/engine/hangul.js';
import { 이웃방향, 자판배열찾기, 평균이웃, 시작수 } from '../src/engine/keyboard.js';
import { 한국어낱말 } from '../src/engine/strength.js';
import { 잇기낱말 } from '../src/engine/words-ko.js';
import { 영어낱말 } from '../src/engine/words-en.js';
import { 흔한비밀번호, 한국어비번낱말, 로마자이름 } from '../src/engine/lists.js';

묶음('한글 → 자판');
확인('사랑해', 한글을자판으로('사랑해'), 'tkfkdgo');
확인('안녕', 한글을자판으로('안녕'), 'dkssud');
확인('안녕하세요', 한글을자판으로('안녕하세요'), 'dkssudgktpdy');
확인('비밀번호', 한글을자판으로('비밀번호'), 'qlalfqjsgh');
확인('고양이', 한글을자판으로('고양이'), 'rhdiddl');
확인('행복 — ㅐ 는 o', 한글을자판으로('행복'), 'godqhr');
확인('콩이', 한글을자판으로('콩이'), 'zhddl');
확인('하람', 한글을자판으로('하람'), 'gkfka');
확인('쌍자음은 대문자 — 빵', 한글을자판으로('빵'), 'Qkd');
확인('ㅖ 는 Shift+p — 계량컵', 한글을자판으로('계량컵'), 'rPfidzjq');
확인('겹모음 — 와이파이', 한글을자판으로('와이파이'), 'dhkdlvkdl');
확인('겹받침 — 닭', 한글을자판으로('닭'), 'ekfr');
확인('숫자·기호는 그대로', 한글을자판으로('사랑해2026!'), 'tkfkdgo2026!');

묶음('자판 → 한글');
확인('tkfkdgo', 자판을한글로('tkfkdgo'), '사랑해');
확인('dkssud123', 자판을한글로('dkssud123'), '안녕123');
확인('받침이 다음 글자로 — dlfrdj(읽어)', 자판을한글로('dlfrdj'), '읽어');
확인('겹받침이 나뉘어 넘어감 — 갈비', 자판을한글로('rkfql'), '갈비');
확인('Shift+t = ㅆ', 자판을한글로('Tkfkdgo'), '싸랑해');
확인('Shift+a 는 그냥 ㅁ', 자판을한글로('Ak'), '마');
확인('자음만', 자판을한글로('zzz'), 'ㅋㅋㅋ');

묶음('한국어 낱말 전부 되돌리기');
let 어긋남 = [];
for (const w of 한국어낱말) if (자판을한글로(한글을자판으로(w)) !== w) 어긋남.push(w);
확인(`한국어 낱말 ${한국어낱말.length}개가 자판 → 한글로 그대로 돌아온다`, 어긋남, []);

묶음('한영 풀이');
참('dkssud 는 뜻 있는 한글', 한영풀이('dkssud').뜻있음);
참('abc 는 뜻 없음', !한영풀이('abc').뜻있음);

묶음('낱말 목록');
확인('잇기 낱말 1024개(2^10) — 경우의 수 계산이 깔끔하다', 잇기낱말.length, 1024);
확인('잇기 낱말은 겹치지 않는다', new Set(잇기낱말).size, 잇기낱말.length);
참('잇기 낱말은 모두 한글 2~3글자', 잇기낱말.every((w) => /^[가-힣]{2,3}$/.test(w)));
확인('영어 낱말 600개, 겹치지 않음', new Set(영어낱말).size, 600);
참('영어 낱말은 소문자 3~12글자', 영어낱말.every((w) => /^[a-z]{3,12}$/.test(w)));
확인('흔한 비밀번호는 대소문자 무시하고 겹치지 않는다', new Set(흔한비밀번호.map((x) => x.toLowerCase())).size, 흔한비밀번호.length);
확인('한국어 비번 낱말은 겹치지 않는다', new Set(한국어비번낱말).size, 한국어비번낱말.length);
참('한국어 비번 낱말은 두 글자 이상', 한국어비번낱말.every((w) => /^[가-힣]{2,}$/.test(w)));
확인('로마자 이름은 겹치지 않는다', new Set(로마자이름).size, 로마자이름.length);

묶음('자판 배열');
참('q-w 이웃', 이웃방향('q', 'w') >= 0);
참('1-q 이웃 (q 는 1·2 아래)', 이웃방향('1', 'q') >= 0 && 이웃방향('q', '2') >= 0);
참('a 는 q·w 아래', 이웃방향('q', 'a') >= 0 && 이웃방향('w', 'a') >= 0);
참('Shift 글자도 같은 자리 — ! 와 Q', 이웃방향('!', 'Q') >= 0);
참('q-p 는 이웃이 아니다', 이웃방향('q', 'p') < 0);
참('z-c 는 이웃이 아니다', 이웃방향('z', 'c') < 0);
확인('qwer 는 자판 배열 한 조각', 자판배열찾기('qwer').map((m) => m.토막), ['qwer']);
확인('1q2w3e4r 는 한 조각(꺾임 7번)', 자판배열찾기('1q2w3e4r').map((m) => [m.토막, m.꺾임]), [['1q2w3e4r', 7]]);
확인('asdfgh 는 한 조각, 꺾임 1번', 자판배열찾기('asdfgh').map((m) => [m.토막, m.꺾임]), [['asdfgh', 1]]);
확인('떨어진 글자는 조각이 없다', 자판배열찾기('qpzm'), []);
참('평균 이웃 수는 4~5', 평균이웃 > 4 && 평균이웃 < 5);
확인('시작할 수 있는 글쇠(Shift 포함)', 시작수, 94);
